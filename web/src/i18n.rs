use leptos::prelude::ArcRwSignal;
use leptos::reactive::traits::{Get, Set};

thread_local! {
    static LOCALE: ArcRwSignal<&'static str> = ArcRwSignal::new("fr");
}

pub fn locale() -> &'static str {
    LOCALE.with(|l| l.get())
}

pub fn set_locale(l: &str) {
    let l: &'static str = match l {
        "en" => "en",
        "es" => "es",
        _ => "fr",
    };
    if let Some(s) = web_sys::window().and_then(|w| w.local_storage().ok().flatten()) {
        let _ = s.set_item("blindall_locale", l);
    }
    let changed = LOCALE.with(|s| {
        let c = s.get() != l;
        s.set(l);
        c
    });
    if changed {
        if let Some(w) = web_sys::window() {
            w.location().reload().ok();
        }
    }
}

pub fn init_locale() {
    if let Some(v) = web_sys::window()
        .and_then(|w| w.local_storage().ok().flatten())
        .and_then(|s| s.get_item("blindall_locale").ok().flatten())
    {
        LOCALE.with(|s| {
            s.set(match v.as_str() {
                "en" => "en",
                "es" => "es",
                _ => "fr",
            })
        });
    }
}

pub fn t<'a>(key: &'a str) -> &'a str {
    match locale() {
        "en" => en(key),
        "es" => es(key),
        _ => fr(key),
    }
}

pub fn set_title(title: Option<&str>) {
    if let Some(d) = web_sys::window().and_then(|w| w.document()) {
        let title = match title {
            Some(t) if t.ends_with("| Blind'All Music") => t.to_string(),
            Some(t) if !t.is_empty() => format!("{t} | Blind'All Music"),
            _ => "Blind'All Music".to_string(),
        };
        d.set_title(&title);
    }
}

pub fn set_title_key(key: &str) {
    set_title(Some(t(key)));
}

