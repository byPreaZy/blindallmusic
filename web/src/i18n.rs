#[allow(dead_code)]
pub fn tr(key: &str, replace: &[(&str, String)]) -> String {
    let base = match t(key) {
        "" => key.to_string(),
        s => s.to_string(),
    };
    replace
        .iter()
        .fold(base, |acc, (k, v)| acc.replace(&format!(":{k}"), v))
}
