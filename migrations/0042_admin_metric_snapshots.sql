-- Periodic snapshots of the admin metrics aggregates so the dashboard can
-- show trends (user growth, subscription growth) instead of only live counts.
-- Written hourly by the server sweeper; read by /api/v1/admin/dashboard/history.

CREATE TABLE IF NOT EXISTS admin_metric_snapshots (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    captured_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    metrics     JSONB       NOT NULL
);

CREATE INDEX IF NOT EXISTS admin_metric_snapshots_captured_at_index
    ON admin_metric_snapshots (captured_at DESC);
