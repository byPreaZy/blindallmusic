-- Stripe subscriptions (Blind'All Plus B2C / Blind'All Pro B2B).
-- Rows are created by the checkout.session.completed webhook (Payment Links,
-- client_reference_id = "<user_id>:<plan>") and kept in sync by
-- customer.subscription.* events.
CREATE TABLE IF NOT EXISTS user_subscriptions (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                   BIGINT NOT NULL,
    plan                      CITEXT NOT NULL,
    status                    CITEXT NOT NULL DEFAULT 'active',
    stripe_checkout_session_id CITEXT NULL,
    stripe_customer_id        CITEXT NULL,
    stripe_subscription_id    CITEXT NULL,
    current_period_end        TIMESTAMPTZ NULL,
    canceled_at               TIMESTAMPTZ NULL,
    created_at                TIMESTAMPTZ NULL,
    updated_at                TIMESTAMPTZ NULL,
    CONSTRAINT user_subscriptions_user_id_foreign FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX IF NOT EXISTS user_subscriptions_session_uidx
    ON user_subscriptions (stripe_checkout_session_id)
    WHERE stripe_checkout_session_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS user_subscriptions_sub_uidx
    ON user_subscriptions (stripe_subscription_id)
    WHERE stripe_subscription_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS user_subscriptions_user_status_index
    ON user_subscriptions (user_id, status);

-- Plus-only perk ledger: one daily-challenge revive per day is enforced via
-- Redis, but the audit trail lives here for abuse checks / refunds.
CREATE TABLE IF NOT EXISTS user_plus_revives (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    day         DATE NOT NULL,
    game_type   CITEXT NOT NULL,
    created_at  TIMESTAMPTZ NULL,
    CONSTRAINT user_plus_revives_user_id_foreign FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT user_plus_revives_unique UNIQUE (user_id, day, game_type)
);
