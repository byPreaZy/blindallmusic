-- =============================================================================
-- Blind'All Music — schéma initial PostgreSQL (port des migrations Laravel
-- database/migrations/*, état final après annulations : banned_at & mosaic_path
-- droppés, password_resets renommé, round_track_listeners &
-- tracks_listened_count jamais présents).
--
-- Choix de portage (parité comportementale visée, pas parité syntaxique) :
--   * TINYINT(1)  → BOOLEAN      (flags is_*, playing, elo_counted…)
--   * INT/SMALLINT→ BIGINT       (le code lit tout en i64)
--   * VARCHAR/TEXT→ CITEXT       (émule utf8mb4_unicode_ci : = / LIKE / ORDER BY
--                                 insensibles à la casse, uniques CI inclus)
--   * JSON        → JSONB
--   * TIMESTAMP   → TIMESTAMPTZ  (le code bind des chrono::DateTime<Utc>)
--   * AUTO_INCREMENT → GENERATED BY DEFAULT AS IDENTITY (l'import pgloader
--     préserve les ids; ALWAYS bloquerait les inserts explicites)
-- =============================================================================

