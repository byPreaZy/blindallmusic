-- ---- Laravel Pulse (monitoring interne — tableaux conservés pour compat) -------
-- MySQL: key_hash CHAR(16) CHARACTER SET binary GENERATED unhex(md5(`key`)) —
-- même forme en PG via decode(md5()) STORED (bytea, 16 octets).

CREATE TABLE IF NOT EXISTS pulse_values (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "timestamp" BIGINT NOT NULL,
    type      CITEXT NOT NULL,
    "key"     TEXT         NOT NULL,
    key_hash  BYTEA GENERATED ALWAYS AS (decode(md5("key"), 'hex')) STORED,
    value     TEXT         NOT NULL,
    CONSTRAINT pulse_values_type_key_hash_unique UNIQUE (type, key_hash)
);
CREATE INDEX IF NOT EXISTS pulse_values_timestamp_index ON pulse_values ("timestamp");
CREATE INDEX IF NOT EXISTS pulse_values_type_index      ON pulse_values (type);

CREATE TABLE IF NOT EXISTS pulse_entries (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "timestamp" BIGINT NOT NULL,
    type      CITEXT NOT NULL,
    "key"     TEXT         NOT NULL,
    key_hash  BYTEA GENERATED ALWAYS AS (decode(md5("key"), 'hex')) STORED,
    value     BIGINT       NULL
);
CREATE INDEX IF NOT EXISTS pulse_entries_timestamp_index ON pulse_entries ("timestamp");
CREATE INDEX IF NOT EXISTS pulse_entries_type_index      ON pulse_entries (type);
CREATE INDEX IF NOT EXISTS pulse_entries_key_hash_index  ON pulse_entries (key_hash);
CREATE INDEX IF NOT EXISTS pulse_entries_timestamp_type_key_hash_value_index
    ON pulse_entries ("timestamp", type, key_hash, value);

CREATE TABLE IF NOT EXISTS pulse_aggregates (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bucket    BIGINT NOT NULL,
    period    BIGINT NOT NULL,
    type      CITEXT NOT NULL,
    "key"     TEXT         NOT NULL,
    key_hash  BYTEA GENERATED ALWAYS AS (decode(md5("key"), 'hex')) STORED,
    aggregate CITEXT NOT NULL,
    value     DOUBLE PRECISION NOT NULL,
    count     BIGINT NULL,
    CONSTRAINT pulse_aggregates_bucket_period_type_aggregate_key_hash_unique
        UNIQUE (bucket, period, type, aggregate, key_hash)
);
CREATE INDEX IF NOT EXISTS pulse_aggregates_period_bucket_index
    ON pulse_aggregates (period, bucket);
CREATE INDEX IF NOT EXISTS pulse_aggregates_type_index
    ON pulse_aggregates (type);
CREATE INDEX IF NOT EXISTS pulse_aggregates_period_type_aggregate_bucket_index
    ON pulse_aggregates (period, type, aggregate, bucket);
