pub fn random_message(kind: &str, locale: &str, index: usize) -> &'static str {
    let pool: &[&str] = match (kind, locale) {
        ("good", "fr") => GOOD_FR,
        ("almost", "fr") => ALMOST_FR,
        ("bad", "fr") => BAD_FR,
        ("good", _) => GOOD_EN,
        ("almost", _) => ALMOST_EN,
        ("bad", _) => BAD_EN,
        _ => BAD_EN,
    };
    pool[index % pool.len()]
}
